def L(addr: str, port: int, ifname: str | None = None, proc: str | None = None):
    return lea.Listener(addr, port, ifname, proc)


def _build_synthetic_policies() -> tuple[dict, dict]:
    """Load (effective, tracked-only) policy through the REAL merge path.

    The temp dir is removed as soon as both dicts are in memory — the policies
    are plain dicts and no longer need the file. This runs at import time so
    that `tests/test_lan_exposure.py` can import ALLOW/CASES and parametrise
    over them; that wrapper's contract is "no case duplicated, no logic
    reimplemented", so the table has to live at module scope.
    """
    with tempfile.TemporaryDirectory(prefix="lan-audit-fixture-") as td:
        p = Path(td) / "lan_exposure_allowlist.local.yaml"
        p.write_text(SYNTHETIC_LOCAL)
        return (
            lea.load_allowlist(local_path=p),
            lea.load_allowlist(local_path=p, use_local=False),
        )


