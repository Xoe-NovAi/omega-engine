# CI-exemption cases are kept out of CASES because they depend on the
# GITHUB_ACTIONS env var being toggled at run time; the pytest wrapper does not
# exercise them (unchanged from the pre-D-616 suite).

results: list[tuple[str, bool, str]] = []


def check(name: str, ok: bool, detail: str = "") -> None:
    results.append((name, ok, detail))


def classify_case(
    name: str, listener: lea.Listener, expect_clean: bool, allow: dict
) -> None:
    """Assert classify() agrees (or disagrees) with the expected verdict."""
    verdict = lea.classify(listener, allow)
    is_clean = verdict is None
    ok = is_clean == expect_clean
    expect = "clean" if expect_clean else "FLAGGED"
    got = "clean" if is_clean else f"flagged({verdict[0]})"
    detail = f"expected={expect:<8} got={got}"
    if ok:
        check(name, True, detail)
    else:
        check(name, False, detail)


def classify_kind_case(
    name: str, listener: lea.Listener, expect_kind: str, allow: dict
) -> None:
    """Assert a listener is reported with a specific KIND (TAILNET vs LAN).

    Needed because "is it clean" and "which class is it" are different
    questions. `tailnet_interfaces` decides the CLASS; the address+port
    allowlist decides whether it is APPROVED. An unknown address sitting on the
    tailnet interface is correctly still FLAGGED — it is just correctly filed as
    TAILNET rather than LAN, and only the kind assertion can see that.
    """
    verdict = lea.classify(listener, allow)
    got = "clean" if verdict is None else verdict[0]
    ok = got == expect_kind
    check(name, ok, f"expected={expect_kind:<8} got={got}")


def main() -> int:
    print("LAN EXPOSURE AUDIT — negative tests")
    print("=" * 74)
    print(f"synthetic tailnet v4 : {SYN_V4}      iface: {SYN_IFACE}")
    print(f"synthetic tailnet v6 : {SYN_V6}")
    print()

    with tempfile.TemporaryDirectory(prefix="lan-audit-test-") as td:
        syn_path = Path(td) / "lan_exposure_allowlist.local.yaml"
        syn_path.write_text(SYNTHETIC_LOCAL)

        print("--- A. classify() against the synthetic host-local override ---")
        for name, listener, expect_clean in CASES:
            classify_case(name, listener, expect_clean, ALLOW)
        for name, listener, expect_kind in KIND_CASES:
            classify_kind_case(name, listener, expect_kind, ALLOW)

        print()
        print("--- B. LOCAL-OVERRIDE PRECEDENCE IS LOAD-BEARING (D-616) ---")
        print("    These assert the merge changes the verdict. Delete the overlay")
        print("    from load_allowlist() and this section goes red.")
        probe = L(SYN_V4, 8016, None, None)
        with_local = lea.classify(probe, ALLOW)
        without_local = lea.classify(probe, TRACKED_ONLY)
        check(
            "override ON  -> approved tailnet bind is clean",
            with_local is None,
            f"got={'clean' if with_local is None else f'flagged({with_local[0]})'}",
        )
        check(
            "override OFF -> same bind is FLAGGED (gate not silently blind)",
            without_local is not None,
            f"got={'clean' if without_local is None else f'flagged({without_local[0]})'}",
        )
        check(
            "verdict genuinely FLIPS with precedence toggled",
            (with_local is None) != (without_local is None),
            "the two policies disagree, which is what makes this discriminating",
        )
        # The tracked template must NOT contain the synthetic address, or the
        # test would be agreeing with the template again.
        check(
            "synthetic addr absent from tracked template",
            SYN_V4 not in str(TRACKED_ONLY),
            "if this fails the template grew a real-looking value",
        )
        # And the merge must be REPLACEMENT, not concatenation: the template's
        # placeholder must not survive into the effective policy.
        check(
            "merge REPLACES tailnet_interfaces (no dead placeholder)",
            lea._as_list(ALLOW.get("tailnet_interfaces")) == [SYN_IFACE],
            f"got={lea._as_list(ALLOW.get('tailnet_interfaces'))}",
        )
        check(
            "merge REPLACES tailnet_addresses (no dead placeholder)",
            lea._as_list(ALLOW.get("tailnet_addresses")) == [SYN_V4, SYN_V6],
            f"got={lea._as_list(ALLOW.get('tailnet_addresses'))}",
        )
        # A key absent from the overlay is inherited from the template.
        check(
            "un-overridden key inherited from template",
            lea._as_list(ALLOW.get("allowed_lan_bindings")) == [],
            "allowed_lan_bindings must stay empty — no LAN bind is approved",
        )
        check(
            "un-overridden key inherits template LAN policy",
            "0.0.0.0" not in str(ALLOW.get("always_exempt_addresses")),
            "wildcard must never become exempt",
        )

        print()
        print("--- C. PLACEHOLDER INTEGRITY (the D-612 signature) ---")
        ph_tracked = lea.find_placeholders(TRACKED_ONLY)
        ph_effective = lea.find_placeholders(ALLOW)
        check(
            "tracked template IS placeholder-only (nothing real ships)",
            len(ph_tracked) > 0,
            f"{len(ph_tracked)} placeholders present in template",
        )
        check(
            "override clears every placeholder from effective policy",
            ph_effective == [],
            f"leaked={[f'{k}={v}' for k, v in ph_effective]}",
        )
        check(
            "find_placeholders detects the D-612 exact value",
            any(v == "<TAILSCALE_IFACE>" for _, v in ph_tracked),
            "guards against the specific regression that started this",
        )
        # A placeholder entry must not approve a real bind.
        classify_case(
            "placeholder address approves nothing",
            L("<N0_TAILNET_IPV4>", 8016, None, None),
            False,
            ALLOW,
        )

        print()
        print("--- D. OVERRIDE DISCOVERY + ENV PRECEDENCE ---")
        _, local_seen = lea.effective_sources(local_path=syn_path)
        check(
            "explicit override path is discovered",
            local_seen == syn_path,
            f"got={local_seen}",
        )
        saved_env = os.environ.pop(lea.LOCAL_OVERRIDE_ENV, None)
        os.environ[lea.LOCAL_OVERRIDE_ENV] = str(syn_path)
        env_allow = lea.load_allowlist()
        check(
            f"${lea.LOCAL_OVERRIDE_ENV} is honoured",
            lea._as_list(env_allow.get("tailnet_interfaces")) == [SYN_IFACE],
            f"got={lea._as_list(env_allow.get('tailnet_interfaces'))}",
        )
        os.environ[lea.LOCAL_OVERRIDE_ENV] = str(Path(td) / "does-not-exist.yaml")
        missing_allow = lea.load_allowlist()
        check(
            "env override pointing nowhere degrades to tracked template",
            lea._as_list(missing_allow.get("tailnet_interfaces"))
            != lea._as_list(env_allow.get("tailnet_interfaces")),
            "no phantom policy from a missing file",
        )
        try:
            lea.load_allowlist(local_path=Path(td) / "does-not-exist.yaml")
            check("explicit missing override raises SystemExit", False, "returned silently")
        except SystemExit:
            check("explicit missing override raises SystemExit", True)
        if saved_env is None:
            os.environ.pop(lea.LOCAL_OVERRIDE_ENV, None)
        else:
            os.environ[lea.LOCAL_OVERRIDE_ENV] = saved_env

        print()
        print("--- E. runner-scoped sshd exemption (PR #5 post-merge CI, 2026-10-03) ---")
        # The exemption must hold ONLY under GITHUB_ACTIONS. Pin both directions:
        # without the env a wildcard :22 must still be caught (Node 0 full
        # strength), and under the env nothing but port 22 may be excused.
        saved_ga = os.environ.pop("GITHUB_ACTIONS", None)
        classify_case("no-CI: wildcard sshd :22 caught", L("0.0.0.0", 22, None, None), False, ALLOW)
        classify_case("no-CI: wildcard v6 sshd :::22 caught", L("::", 22, None, None), False, ALLOW)
        os.environ["GITHUB_ACTIONS"] = "true"
        classify_case("CI runner: wildcard sshd :22 exempt", L("0.0.0.0", 22, None, None), True, ALLOW)
        classify_case("CI runner: wildcard v6 sshd :::22 exempt", L("::", 22, None, None), True, ALLOW)
        classify_case("CI runner: wildcard :2222 still caught", L("0.0.0.0", 2222, None, None), False, ALLOW)
        classify_case("CI runner: wildcard nfsd 2049 still caught", L("0.0.0.0", 2049, None, None), False, ALLOW)
        classify_case(
            "CI runner: LAN sshd on real IP still caught",
            L("10.0.3.1", 22, None, "sshd"),
            False,
            ALLOW,
        )
        if saved_ga is None:
            os.environ.pop("GITHUB_ACTIONS", None)
        else:
            os.environ["GITHUB_ACTIONS"] = saved_ga

    print("=" * 74)
    for name, ok, detail in results:
        status = f"{PASS}PASS{NC}" if ok else f"{FAIL}FAIL{NC}"
        print(f"  [{status}] {name:<52} {detail}")

    total = len(results)
    failures = [n for n, ok, _ in results if not ok]
    print("=" * 74)
    if failures:
        print(f"{FAIL}RESULT: FAIL{NC} — {len(failures)}/{total} negative tests failed:")
        for f in failures:
            print(f"  - {f}")
        return 1
    print(f"{PASS}RESULT: PASS{NC} — {total}/{total} negative tests green.")
    print()
    print("Section B is the anti-D-612 assertion: the approved-address cases are")
    print("fed by a TEMP synthetic override, not by the tracked template, and the")
    print("verdict is required to FLIP when local precedence is disabled. A test")
    print("whose fixtures move with the implementation cannot catch a gate that")
    print("went blind — this one can.")
    return 0


if __name__ == "__main__":
    sys.exit(main())